-- Esquema de la base programatss (PostgreSQL).
-- Las columnas coinciden con las del importador (src/utils/importador.ts) y con la base
-- Base_Limpia_Titulados_Empleadores.xlsx. Un valor NULL significa "sin respuesta" o "no aplica".
-- Se puede ejecutar varias veces: no borra datos existentes.

CREATE TABLE IF NOT EXISTS titulados (
  id                            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edad                          TEXT NOT NULL,
  genero                        TEXT NOT NULL,
  formacion_complementaria      TEXT NOT NULL,
  nivel_realizado               TEXT,
  lugar_realizado               TEXT,
  financiamiento                TEXT,
  programa                      TEXT,
  interes_posgrado              TEXT,
  area_interes                  TEXT,
  institucion_preferida         TEXT,
  opinion_posgrado_fcyt         SMALLINT CHECK (opinion_posgrado_fcyt BETWEEN 1 AND 4),
  anios_vida_profesional        DOUBLE PRECISION CHECK (anios_vida_profesional BETWEEN 0 AND 60),
  anios_desempleado             DOUBLE PRECISION CHECK (anios_desempleado BETWEEN 0 AND 60),
  situacion_laboral             TEXT NOT NULL,
  empresa                       TEXT,
  rubro                         TEXT,
  sector                        TEXT,
  departamento                  TEXT,
  actividades                   TEXT[] NOT NULL DEFAULT '{}',
  cargo                         TEXT,
  pertinencia_labores           SMALLINT CHECK (pertinencia_labores BETWEEN 1 AND 4),
  antiguedad_trabajo            TEXT,
  medio_obtencion               TEXT,
  remuneracion                  TEXT,
  origen_emprendimiento         TEXT,
  entregable_negocio            TEXT,
  financiamiento_negocio        TEXT,
  satisfaccion_negocio          TEXT,
  importancia_formacion_negocio TEXT,
  primer_empleo                 TEXT,
  razon_no_trabaja              TEXT,
  trabajo_previo_sistemas       TEXT,
  tiempo_primer_empleo          TEXT,
  numero_empleos                TEXT,
  satisfaccion_global           SMALLINT CHECK (satisfaccion_global BETWEEN 1 AND 4),
  concordancia_formacion        SMALLINT CHECK (concordancia_formacion BETWEEN 1 AND 4),
  aspectos_utiles               TEXT[] NOT NULL DEFAULT '{}',
  aspectos_mejorar              TEXT[] NOT NULL DEFAULT '{}',
  asignaturas_ventaja           TEXT[] NOT NULL DEFAULT '{}',
  asignaturas_no_utiles         TEXT[] NOT NULL DEFAULT '{}',
  red_contactos                 TEXT,
  origen                        TEXT NOT NULL CHECK (origen IN ('base_oficial', 'formulario')),
  created_at                    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS empleadores (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizacion             TEXT NOT NULL,
  tipo                     TEXT NOT NULL,
  tamano                   TEXT NOT NULL,
  rubro                    TEXT,
  contrato_5_anios         TEXT,
  posibilidad_contratacion TEXT,
  nivel_demandado          TEXT,
  medio_convocatoria       TEXT,
  cargos                   TEXT[] NOT NULL DEFAULT '{}',
  tendencias               TEXT,
  habilidades              TEXT,
  -- Respuestas a las 18 afirmaciones (escala de LIKERT_EMPLEADOR)
  item_01 TEXT, item_02 TEXT, item_03 TEXT, item_04 TEXT, item_05 TEXT, item_06 TEXT,
  item_07 TEXT, item_08 TEXT, item_09 TEXT, item_10 TEXT, item_11 TEXT, item_12 TEXT,
  item_13 TEXT, item_14 TEXT, item_15 TEXT, item_16 TEXT, item_17 TEXT, item_18 TEXT,
  origen                   TEXT NOT NULL CHECK (origen IN ('base_oficial', 'formulario')),
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS items_empleadores (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo     TEXT NOT NULL UNIQUE,
  afirmacion TEXT NOT NULL,
  origen     TEXT NOT NULL CHECK (origen IN ('base_oficial', 'formulario')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
