-- Esquema normalizado (3FN) de la base programatss (PostgreSQL).
-- Los nombres de los datos coinciden con los del importador (src/utils/importador.ts) y con la base
-- Base_Limpia_Titulados_Empleadores.xlsx. Un valor NULL significa "sin respuesta" o "no aplica".
-- Se puede ejecutar varias veces: no borra datos existentes.
-- Diagrama entidad-relación: docs/modelo_er.md

-- ===========================================================================
-- Catálogos
-- ===========================================================================
-- Valores válidos de las preguntas de opción. Los carga npm run db:seed desde
-- src/data/catalogos.ts, en el orden de ese archivo (el id sigue ese orden).
-- Algunos catálogos los comparten dos preguntas (p. ej. rubros: titulados y empleadores);
-- qué subconjunto admite cada pregunta lo valida la API con src/utils/validacion.ts.

CREATE TABLE IF NOT EXISTS areas_posgrado (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Instituciones donde se cursó un posgrado o donde se preferiría cursarlo
CREATE TABLE IF NOT EXISTS instituciones (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS niveles_posgrado (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Financiamiento del posgrado y del emprendimiento
CREATE TABLE IF NOT EXISTS fuentes_financiamiento (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Rubros de titulados y de empleadores
CREATE TABLE IF NOT EXISTS rubros (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Sector del titulado y tipo de organización del empleador (Privado / Público)
CREATE TABLE IF NOT EXISTS sectores (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cargos_titulado (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cargos_empleador (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Asignaturas con ventaja competitiva o de poca utilidad
CREATE TABLE IF NOT EXISTS asignaturas (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Aspectos útiles de la carrera y aspectos a mejorar
CREATE TABLE IF NOT EXISTS aspectos_carrera (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS actividades (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

-- Escala de 4 puntos de los titulados: el id ES el valor (1 = Totalmente en desacuerdo … 4)
CREATE TABLE IF NOT EXISTS escala_likert_titulado (
  id     SMALLINT PRIMARY KEY CHECK (id BETWEEN 1 AND 4),
  nombre TEXT NOT NULL UNIQUE
);

-- Escala de las 18 afirmaciones de empleadores (TA, PA, TD, NS = No sabe)
CREATE TABLE IF NOT EXISTS escala_likert_empleador (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE CHECK (codigo IN ('TA', 'PA', 'TD', 'NS')),
  nombre TEXT NOT NULL UNIQUE
);

-- ===========================================================================
-- Encuestas
-- ===========================================================================

CREATE TABLE IF NOT EXISTS titulados (
  id                            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  edad                          TEXT NOT NULL CHECK (edad IN ('19 - 22 años', '23 - 26 años', '27 - 30 años', '31 - 34 años', '35 años o más')),
  genero                        TEXT NOT NULL CHECK (genero IN ('Hombre', 'Mujer')),
  formacion_complementaria      TEXT NOT NULL CHECK (formacion_complementaria IN ('Sí', 'No')),
  nivel_realizado_id            SMALLINT REFERENCES niveles_posgrado (id),
  lugar_realizado_id            SMALLINT REFERENCES instituciones (id),
  financiamiento_id             SMALLINT REFERENCES fuentes_financiamiento (id),
  programa                      TEXT,
  interes_posgrado              TEXT CHECK (interes_posgrado IN ('Sí', 'No')),
  area_interes_id               SMALLINT REFERENCES areas_posgrado (id),
  institucion_preferida_id      SMALLINT REFERENCES instituciones (id),
  opinion_posgrado_fcyt_id      SMALLINT REFERENCES escala_likert_titulado (id),
  anios_vida_profesional        DOUBLE PRECISION CHECK (anios_vida_profesional BETWEEN 0 AND 60),
  anios_desempleado             DOUBLE PRECISION CHECK (anios_desempleado BETWEEN 0 AND 60),
  situacion_laboral             TEXT NOT NULL CHECK (situacion_laboral IN ('Trabaja en una organización', 'Emprendimiento propio', 'No trabaja')),
  empresa                       TEXT,
  rubro_id                      SMALLINT REFERENCES rubros (id),
  sector_id                     SMALLINT REFERENCES sectores (id),
  departamento                  TEXT CHECK (departamento IN ('Cochabamba', 'La Paz', 'Santa Cruz', 'Oruro', 'Potosí', 'Chuquisaca', 'Tarija', 'Beni', 'Pando', 'Extranjero')),
  cargo_id                      SMALLINT REFERENCES cargos_titulado (id),
  pertinencia_labores_id        SMALLINT REFERENCES escala_likert_titulado (id),
  antiguedad_trabajo            TEXT CHECK (antiguedad_trabajo IN ('Menos de 1 año', 'Entre 1 a 2 años', 'Entre 2 a 5 años', 'Entre 5 a 8 años', 'Entre 8 a 11 años', 'Entre 11 a 15 años', 'Entre 15 a 20 años', 'Entre 20 a 25 años', 'Más de 25 años')),
  medio_obtencion               TEXT CHECK (medio_obtencion IN ('Postulación competitiva (convocatorias públicas y privadas)', 'Recomendación de terceros', 'Internet y redes sociales', 'Medios escritos o audiovisuales', 'Otros')),
  remuneracion                  TEXT CHECK (remuneracion IN ('Menor a Bs. 2.500', 'Entre Bs. 2.500 - Bs. 3.500', 'Entre Bs. 3.501 - Bs. 5.000', 'Entre Bs. 5.001 - Bs. 7.000', 'Entre Bs. 7.001 - Bs. 10.000', 'Más de Bs. 10.000')),
  origen_emprendimiento         TEXT CHECK (origen_emprendimiento IN ('Idea propia', 'Idea conjunta con compañeros', 'StartUp', 'Otro')),
  entregable_negocio            TEXT CHECK (entregable_negocio IN ('Producto', 'Servicio', 'Ambos')),
  financiamiento_negocio_id     SMALLINT REFERENCES fuentes_financiamiento (id),
  satisfaccion_negocio          TEXT CHECK (satisfaccion_negocio IN ('Satisfecho', 'Algo satisfecho', 'Insatisfecho')),
  importancia_formacion_negocio TEXT CHECK (importancia_formacion_negocio IN ('Muy importante', 'Importante', 'Poco importante')),
  primer_empleo                 TEXT CHECK (primer_empleo IN ('Sí', 'No')),
  razon_no_trabaja              TEXT CHECK (razon_no_trabaja IN ('Incumplimiento de requisitos en habilidades específicas (idiomas, softwares, etc)', 'Demanda laboral inexistente', 'Incumplimiento de requisitos de experiencia previa', 'Ofertas laborales con remuneración muy bajas', 'Red de contactos limitada', 'Habilidades deficientes en las entrevistas', 'Otro')),
  trabajo_previo_sistemas       TEXT CHECK (trabajo_previo_sistemas IN ('Sí', 'No')),
  tiempo_primer_empleo          TEXT CHECK (tiempo_primer_empleo IN ('Ya trabajaba antes de titularse', 'Menos de 1 mes', 'Entre 1 - 4 meses', 'Entre 4 - 8 meses', 'Entre 8 - 12 meses', 'Más de 12 meses')),
  numero_empleos                TEXT CHECK (numero_empleos IN ('1', '2', '3', 'Más de 3')),
  satisfaccion_global_id        SMALLINT REFERENCES escala_likert_titulado (id),
  concordancia_formacion_id     SMALLINT REFERENCES escala_likert_titulado (id),
  red_contactos                 TEXT CHECK (red_contactos IN ('Sí', 'No')),
  origen                        TEXT NOT NULL CHECK (origen IN ('base_oficial', 'formulario')),
  created_at                    TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- Regla de limpieza del informe (también la aplican el importador y el formulario)
  CONSTRAINT desempleo_no_supera_vida_profesional
    CHECK (anios_desempleado <= anios_vida_profesional),
  -- Preguntas condicionales: solo tienen respuesta cuando aplican
  CONSTRAINT posgrado_solo_si_lo_curso
    CHECK (formacion_complementaria = 'Sí'
           OR (nivel_realizado_id IS NULL AND lugar_realizado_id IS NULL AND financiamiento_id IS NULL)),
  CONSTRAINT empleo_solo_si_trabaja
    CHECK (situacion_laboral <> 'No trabaja'
           OR (empresa IS NULL AND departamento IS NULL AND antiguedad_trabajo IS NULL AND medio_obtencion IS NULL)),
  CONSTRAINT razon_no_trabaja_solo_si_no_trabaja
    CHECK (situacion_laboral = 'No trabaja' OR razon_no_trabaja IS NULL),
  CONSTRAINT negocio_solo_si_emprende
    CHECK (situacion_laboral = 'Emprendimiento propio'
           OR (origen_emprendimiento IS NULL AND entregable_negocio IS NULL AND financiamiento_negocio_id IS NULL
               AND satisfaccion_negocio IS NULL AND importancia_formacion_negocio IS NULL))
);

CREATE TABLE IF NOT EXISTS empleadores (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizacion             TEXT NOT NULL CHECK (length(btrim(organizacion)) >= 2),
  tipo_id                  SMALLINT NOT NULL REFERENCES sectores (id),
  tamano                   TEXT NOT NULL CHECK (tamano IN ('Micro', 'Pequeña', 'Mediana', 'Grande')),
  rubro_id                 SMALLINT REFERENCES rubros (id),
  contrato_5_anios         TEXT CHECK (contrato_5_anios IN ('Sí', 'No')),
  posibilidad_contratacion TEXT CHECK (posibilidad_contratacion IN ('Alta probabilidad', 'Depende del crecimiento / proyectos', 'No prevista actualmente')),
  nivel_demandado          TEXT CHECK (nivel_demandado IN ('Licenciatura', 'Diplomado', 'Especialidad', 'Maestría')),
  medio_convocatoria       TEXT CHECK (medio_convocatoria IN ('Internet y redes sociales', 'Postulación competitiva', 'Recomendación de terceros', 'Medios escritos y audiovisuales', 'Oferta profesional personal', 'Otros')),
  tendencias               TEXT,
  habilidades              TEXT,
  origen                   TEXT NOT NULL CHECK (origen IN ('base_oficial', 'formulario')),
  created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS items_empleadores (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo     TEXT NOT NULL UNIQUE CHECK (codigo ~ '^item_[0-9]{2}$'),
  afirmacion TEXT NOT NULL,
  origen     TEXT NOT NULL CHECK (origen IN ('base_oficial', 'formulario')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Respuesta de un empleador a una afirmación. Una afirmación sin respuesta no tiene fila.
CREATE TABLE IF NOT EXISTS respuestas_empleador (
  empleador_id INTEGER  NOT NULL REFERENCES empleadores (id) ON DELETE CASCADE,
  item_id      INTEGER  NOT NULL REFERENCES items_empleadores (id),
  valor_id     SMALLINT NOT NULL REFERENCES escala_likert_empleador (id),
  PRIMARY KEY (empleador_id, item_id)
);

-- ===========================================================================
-- Preguntas de selección múltiple
-- ===========================================================================
-- Una fila por opción elegida. "orden" conserva el orden en que se respondió
-- (posición 1, 2, 3…), para que las vistas devuelvan las listas tal como en la base oficial.
-- Borrar un titulado o empleador borra sus selecciones (CASCADE); una opción de catálogo
-- en uso no se puede borrar.

CREATE TABLE IF NOT EXISTS titulado_actividad (
  titulado_id  INTEGER  NOT NULL REFERENCES titulados (id) ON DELETE CASCADE,
  actividad_id SMALLINT NOT NULL REFERENCES actividades (id),
  orden        SMALLINT NOT NULL CHECK (orden >= 1),
  PRIMARY KEY (titulado_id, actividad_id),
  UNIQUE (titulado_id, orden)
);

CREATE TABLE IF NOT EXISTS titulado_aspecto_util (
  titulado_id INTEGER  NOT NULL REFERENCES titulados (id) ON DELETE CASCADE,
  aspecto_id  SMALLINT NOT NULL REFERENCES aspectos_carrera (id),
  orden       SMALLINT NOT NULL CHECK (orden >= 1),
  PRIMARY KEY (titulado_id, aspecto_id),
  UNIQUE (titulado_id, orden)
);

CREATE TABLE IF NOT EXISTS titulado_aspecto_mejorar (
  titulado_id INTEGER  NOT NULL REFERENCES titulados (id) ON DELETE CASCADE,
  aspecto_id  SMALLINT NOT NULL REFERENCES aspectos_carrera (id),
  orden       SMALLINT NOT NULL CHECK (orden >= 1),
  PRIMARY KEY (titulado_id, aspecto_id),
  UNIQUE (titulado_id, orden)
);

CREATE TABLE IF NOT EXISTS titulado_asignatura_ventaja (
  titulado_id   INTEGER  NOT NULL REFERENCES titulados (id) ON DELETE CASCADE,
  asignatura_id SMALLINT NOT NULL REFERENCES asignaturas (id),
  orden         SMALLINT NOT NULL CHECK (orden >= 1),
  PRIMARY KEY (titulado_id, asignatura_id),
  UNIQUE (titulado_id, orden)
);

CREATE TABLE IF NOT EXISTS titulado_asignatura_no_util (
  titulado_id   INTEGER  NOT NULL REFERENCES titulados (id) ON DELETE CASCADE,
  asignatura_id SMALLINT NOT NULL REFERENCES asignaturas (id),
  orden         SMALLINT NOT NULL CHECK (orden >= 1),
  PRIMARY KEY (titulado_id, asignatura_id),
  UNIQUE (titulado_id, orden)
);

CREATE TABLE IF NOT EXISTS empleador_cargo (
  empleador_id INTEGER  NOT NULL REFERENCES empleadores (id) ON DELETE CASCADE,
  cargo_id     SMALLINT NOT NULL REFERENCES cargos_empleador (id),
  orden        SMALLINT NOT NULL CHECK (orden >= 1),
  PRIMARY KEY (empleador_id, cargo_id),
  UNIQUE (empleador_id, orden)
);

